// 生成单个章节
async function generateChapter(chapter) {
    const children = [
        // 标题
        new Paragraph({
            children: [
                new TextRun({
                    text: chapter.title,
                    bold: true,
                    size: 48,
                }),
            ],
            alignment: AlignmentType.CENTER,
            spacing: { after: 400 }
        })
    ];

    // 添加各小节
    for (const section of chapter.sections) {
        // 小节标题
        children.push(new Paragraph({
            children: [
                new TextRun({
                    text: section.heading,
                    bold: true,
                    size: 32,
                }),
            ],
            spacing: { before: 240, after: 120 }
        }));

        // 内容段落
        for (const text of section.content) {
            children.push(new Paragraph({
                children: [
                    new TextRun({
                        text: text,
                        size: 24,
                    }),
                ],
                spacing: { line: 360, after: 120 }
            }));
        }
    }

    const doc = new Document({
        sections: [{
            properties: {},
            children: children
        }]
    });

    const buffer = await Packer.toBuffer(doc);
    const filePath = outputDir + "\\" + chapter.name + ".docx";
    fs.writeFileSync(filePath, buffer);
    console.log("✓ 已生成: " + chapter.name + ".docx");
}

